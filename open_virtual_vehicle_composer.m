function open_virtual_vehicle_composer(vehicleName)
% OPEN_VIRTUAL_VEHICLE_COMPOSER Launches Virtual Vehicle Composer with BEV specs preloaded
%
% Usage:
%   open_virtual_vehicle_composer;                     % Uses default Tata Nexon EV LR
%   open_virtual_vehicle_composer('MG_WINDSOR_EV');   % Uses MG Windsor EV
%   open_virtual_vehicle_composer('HYUNDAI_IONIQ_5'); % Uses Hyundai Ioniq 5
%
% This utility:
%   1. Loads vehicle specifications from vehicleDatabase into MATLAB base workspace
%   2. Formats parameters matching Virtual Vehicle Composer's parameter fields
%   3. Launches the MathWorks Virtual Vehicle Composer App
%   4. Prints step-by-step instructions for demonstrating the workflow to evaluators

    if nargin < 1 || isempty(vehicleName)
        vehicleName = 'TATA_NEXON_EV_LR';
    end

    % Add project paths
    projDir = fullfile(fileparts(mfilename('fullpath')), 'SS Project', 'extracted', ...
        'Simscape-Battery-Electric-Vehicle-Model-R2026a', 'BEV_Route_Optimization');
    addpath(projDir);
    addpath(fullfile(projDir, 'VehicleDatabase'));

    % Retrieve vehicle specs from database
    try
        v = vehicleDatabase('get', vehicleName);
    catch
        v = vehicleDatabase('get', 'TATA_NEXON_EV_LR');
    end

    % Preload variables into base workspace for Simulink & Virtual Vehicle Composer
    assignin('base', 'veh_mass', v.VehicleMass_kg);
    assignin('base', 'veh_cd', v.DragCoeff_Cd);
    assignin('base', 'veh_area', v.FrontalArea_m2);
    assignin('base', 'veh_crr', v.RollingResistance_Crr);
    assignin('base', 'veh_rw', v.WheelRadius_m);
    assignin('base', 'veh_gear', v.GearRatio);
    assignin('base', 'batt_cap_kwh', v.BatteryCapacity_kWh);
    assignin('base', 'batt_usable_kwh', v.UsableCapacity_kWh);
    assignin('base', 'batt_nom_v', v.NominalVoltage_V);
    assignin('base', 'motor_power_kw', v.MotorPeakPower_kW);
    assignin('base', 'motor_torque_nm', v.MotorPeakTorque_Nm);
    assignin('base', 'max_speed_kmh', v.MaxSpeed_kmh);

    fprintf('===================================================================\n');
    fprintf('          VIRTUAL VEHICLE COMPOSER — BEV MODEL SPECIFICATIONS      \n');
    fprintf('===================================================================\n');
    fprintf('  Selected Vehicle     : %s %s (%s)\n', v.Manufacturer, v.Model, v.Variant);
    fprintf('  Curb Mass            : %.1f kg\n', v.VehicleMass_kg);
    fprintf('  Drag Coefficient (Cd): %.3f\n', v.DragCoeff_Cd);
    fprintf('  Frontal Area         : %.2f m^2 (Effective Cd*A = %.3f m^2)\n', v.FrontalArea_m2, v.DragCoeff_Cd * v.FrontalArea_m2);
    fprintf('  Rolling Resistance   : %.4f\n', v.RollingResistance_Crr);
    fprintf('  Wheel Radius         : %.3f m\n', v.WheelRadius_m);
    fprintf('  Motor Peak Power     : %.1f kW (%.1f Nm peak torque)\n', v.MotorPeakPower_kW, v.MotorPeakTorque_Nm);
    fprintf('  Battery Capacity     : %.1f kWh (Usable: %.1f kWh)\n', v.BatteryCapacity_kWh, v.UsableCapacity_kWh);
    fprintf('  Nominal Voltage      : %.1f V\n', v.NominalVoltage_V);
    fprintf('  Drivetrain Ratio     : %.2f:1 (Efficiency: %.0f%%)\n', v.GearRatio, v.DrivetrainEfficiency*100);
    fprintf('===================================================================\n\n');

    fprintf('All parameters exported to base workspace.\n');
    fprintf('Launching Virtual Vehicle Composer app...\n');

    try
        virtualVehicleComposer;
        fprintf('\n>>> Virtual Vehicle Composer App launched successfully! <<<\n\n');
    catch ME
        warning('Could not launch virtualVehicleComposer GUI: %s', ME.message);
        fprintf('Tip: Open it from MATLAB Apps Gallery -> Virtual Vehicle Composer\n\n');
    end

    fprintf('STEPS TO EXPLAIN IN VIRTUAL VEHICLE COMPOSER:\n');
    fprintf('  1. Architecture: Select "Electric Vehicle" (BEV) -> Single Motor / Rear Axle\n');
    fprintf('  2. Vehicle Body: Set Mass = veh_mass, Cd = veh_cd, Frontal Area = veh_area\n');
    fprintf('  3. Powertrain  : Set Motor Power = motor_power_kw kW, Gear Ratio = veh_gear\n');
    fprintf('  4. Energy Storage: Select Battery Table-Based -> Capacity = batt_cap_kwh kWh\n');
    fprintf('  5. Scenario / Drive Cycle: Select "From Workspace" or "MAT-File"\n');
    fprintf('     -> Point to "route_drive_cycle.mat" generated by export_route_to_simulink\n');
    fprintf('  6. Export & Simulate: Click "Export" -> Run simulation to obtain SOC and kWh\n');
    fprintf('===================================================================\n');
end
