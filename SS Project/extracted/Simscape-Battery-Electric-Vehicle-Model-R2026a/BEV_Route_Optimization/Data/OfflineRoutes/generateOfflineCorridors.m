        'Distance_km', s_fine_blr, ...
        'Elevation_m', interp1(d_blr, elev_blr, s_fine_blr, 'pchip'), ...
        'SpeedLimit_kmh', interp1(d_blr, spd_blr, s_fine_blr, 'nearest'), ...
        'TrafficSpeed_kmh', interp1(d_blr, traf_blr, s_fine_blr, 'linear'), ...
        'Latitude', interp1(d_blr, linspace(12.9716, 12.2958, numel(d_blr))', s_fine_blr, 'linear'), ...
        'Longitude', interp1(d_blr, linspace(77.5946, 76.6394, numel(d_blr))', s_fine_blr, 'linear'), ...
        'Waypoints_Distance_km', d_blr, ...
        'Waypoints_Elevation_m', elev_blr, ...
