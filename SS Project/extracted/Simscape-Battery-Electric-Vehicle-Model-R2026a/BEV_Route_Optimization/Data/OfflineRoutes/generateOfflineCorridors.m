        'Longitude', interp1(d_urb, linspace(72.8464, 72.8147, numel(d_urb))', s_fine_urb, 'linear'), ...
        'Waypoints_Distance_km', d_urb, ...
        'Waypoints_Elevation_m', elev_urb, ...
        'Waypoints_RoadType', {road_urb}, ...
        'StopEvents_Distance_km', [4.5; 11.8; 18.2; 25.5; 31.0], ... % Signals & toll
        'ChargingStations', chargers_urb ...
    );

    %% Optionally save individual .mat files
    if saveMatFiles
        fnames = fieldnames(routes);
        for i = 1:numel(fnames)
            routeData = routes.(fnames{i}); %#ok<NASGU>
            savePath = fullfile(dataDir, [fnames{i} '.mat']);
            save(savePath, 'routeData');
            fprintf('Saved route data to %s\n', savePath);
        end
