    elev_urb = [12, 10, 8, 6, 8, 10]';
    spd_urb = [40, 50, 70, 80, 50, 40]';
    traf_urb = [22, 28, 45, 60, 30, 20]'; % Heavy city traffic
    road_urb = {'City_Street', 'Arterial_Road', 'Bandra_Worli_SeaLink', 'Coastal_Road_Expressway', 'Arterial_Road', 'Heritage_Zone'}';

